def main():
    OUT.mkdir(exist_ok=True)
    ensure_packages()

    print("\n=== Downloading genomes from NCBI ===")
    genomes, failed = load_genomes()
    if not genomes:
        raise SystemExit("No genome could be downloaded. Check the internet connection and the accessions.")

    print("\n=== Loading HMM profiles ===")
    hmms = load_hmms()
    if not hmms:
        raise SystemExit("No HMM profiles available; cannot continue (see tip above).")

    print("\n=== Predicting genes and searching proteins ===")
    all_rows, proteins_per_genome, protein_info = [], {}, []
    for i, (name, contigs) in enumerate(genomes.items(), 1):
        prots = predict_proteins(contigs)
        proteins_per_genome[name] = len(prots)
        rows = search_proteins(name, prots, hmms)
        for r in rows:
            p = prots[r["prot_idx"]]
            r.update({"contig": p["contig"], "start": p["start"], "end": p["end"], "strand": p["strand"],
                      "length_aa": len(p["protein"])})
        all_rows += rows
        print(f"[{i}/{len(genomes)}] {name}: {len(prots):,} proteins, {len(rows)} domain hits")

    hits = pd.DataFrame(all_rows)
    hits.to_csv(OUT / "domain_hits.csv", index=False)

    table = build_feature_table(hits, list(genomes), proteins_per_genome)
    score = chitin_score(table)
    table["chitin_score"] = score
    table.sort_values("chitin_score", ascending=False).to_csv(OUT / "chitin_feature_table.csv")

    print("\n=== Ranking ===")
    show_cols = ["chitin_score", "chitinases_GH18_GH19", "chitinases_with_binding_module",
                 "AA10_LPMO", "GH20_hexosaminidase", "GH46_chitosanase"]
    print(table.sort_values("chitin_score", ascending=False)[show_cols].to_string())
    if failed:
        print("\nGenomes that could not be downloaded:", failed)
        pd.Series(failed, name="error").to_csv(OUT / "failed_downloads.csv")

    plot_heatmap(table.drop(columns=["chitin_score"]), score)
    train_model(table.drop(columns=["chitin_score"]), score)

    print(f"\nDone. Tables and figures are in '{OUT}'.")
    print("Reminder: gene presence indicates potential, not proof, of chitin degradation; "
          "confirm key strains with a chitin plate or enzyme assay.")
    try:
        from google.colab import files
        shutil.make_archive("results", "zip", OUT)
        files.download("results.zip")
    except ImportError:
        pass


if __name__ == "__main__":
    main()