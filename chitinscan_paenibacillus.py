def fetch_hmm(acc):
    import requests
    urls = [f"https://www.ebi.ac.uk/interpro/api/entry/pfam/{acc}?annotation=hmm",
            f"https://www.ebi.ac.uk/interpro/wwwapi/entry/pfam/{acc}?annotation=hmm"]
    last = None
    for u in urls:
        try:
            r = requests.get(u, timeout=120)
            if r.status_code == 200 and r.content:
                data = r.content
                if data[:2] == b"\x1f\x8b":
                    data = gzip.decompress(data)
                if data.startswith(b"HMMER"):
                    return data
                last = f"unexpected content from {u}"
            else:
                last = f"HTTP {r.status_code} from {u}"
        except Exception as e:
            last = repr(e)
    raise RuntimeError(f"could not download {acc}: {last}")


def load_hmms():
    import pyhmmer
    HMM_DIR.mkdir(exist_ok=True)
    hmms, missing = [], []
    for acc, feat in PROFILES.items():
        path = HMM_DIR / f"{acc}.hmm"
        try:
            if not path.exists():
                path.write_bytes(fetch_hmm(acc))
            with pyhmmer.plan7.HMMFile(str(path)) as hf:
                h = next(iter(hf))
            hmms.append((feat, h))
            print(f"  profile {acc} -> {feat} (model name: {h.name.decode() if isinstance(h.name, bytes) else h.name})")
        except Exception as e:
            missing.append(acc)
            print(f"  WARNING profile {acc} ({feat}) unavailable: {e}")
    if missing:
        print("\nTip: you can place your own HMM files named PFxxxxx.hmm in the 'hmm_db' folder "
              "(Pfam download page) and re-run.")
    return hmms


def search_proteins(genome_name, prots, hmms):
    """Return rows (genome, prot_idx, feature, score, evalue) for hits passing the cut-offs."""
    import pyhmmer
    if not prots:
        return []
    amino = pyhmmer.easel.Alphabet.amino()
    block = pyhmmer.easel.DigitalSequenceBlock(
        amino, [pyhmmer.easel.TextSequence(name=str(i).encode(), sequence=p["protein"]).digitize(amino)
                for i, p in enumerate(prots)])
    models = [h for _, h in hmms]
    use_ga = all(getattr(h.cutoffs, "gathering", None) is not None for h in models)
    kw = {"bit_cutoffs": "gathering"} if use_ga else {"E": 1e-5}
    rows = []
    for (feat, _), tophits in zip(hmms, pyhmmer.hmmsearch(models, block, cpus=0, **kw)):
        for hit in tophits:
            if use_ga and not hit.included:
                continue
            if not use_ga and hit.evalue > 1e-5:
                continue
            name = hit.name.decode() if isinstance(hit.name, bytes) else hit.name
            rows.append({"genome": genome_name, "prot_idx": int(name), "feature": feat,
                         "bitscore": round(hit.score, 1), "evalue": hit.evalue})
    return rows


