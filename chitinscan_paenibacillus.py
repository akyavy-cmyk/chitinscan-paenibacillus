def fetch_fasta(acc, tries=3):
    import requests
    url = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/efetch.fcgi"
    params = {"db": "nuccore", "id": acc, "rettype": "fasta", "retmode": "text", "tool": "chitin_screen"}
    if EMAIL:
        params["email"] = EMAIL
    last = None
    for k in range(tries):
        try:
            r = requests.get(url, params=params, timeout=180)
            if r.status_code == 200 and r.text.startswith(">"):
                return r.text
            last = f"HTTP {r.status_code}: {r.text[:100]!r}"
        except Exception as e:  # network problems
            last = repr(e)
        time.sleep(2 * (k + 1))
    raise RuntimeError(f"could not download {acc}: {last}")


def parse_fasta_text(text):
    seqs, name, buf = {}, None, []
    for line in text.splitlines():
        if line.startswith(">"):
            if name:
                seqs[name] = "".join(buf).upper()
            name, buf = line[1:].split()[0], []
        elif name:
            buf.append(line.strip())
    if name:
        seqs[name] = "".join(buf).upper()
    return seqs


def load_genomes():
    GENOME_DIR.mkdir(exist_ok=True)
    genomes, failed = {}, {}
    for i, (name, accs) in enumerate(GENOMES.items(), 1):
        contigs = {}
        try:
            for acc in as_list(accs):
                path = GENOME_DIR / f"{acc}.fasta"
                if not path.exists():
                    path.write_text(fetch_fasta(acc))
                    time.sleep(0.4)     # stay under NCBI's 3 requests/second limit
                contigs.update(parse_fasta_text(path.read_text()))
            genomes[name] = contigs
            print(f"[{i}/{len(GENOMES)}] {name}: {len(contigs)} sequence(s), "
                  f"{sum(len(s) for s in contigs.values()):,} bp")
        except Exception as e:
            failed[name] = str(e)
            print(f"[{i}/{len(GENOMES)}] {name}: FAILED - {e}")
    return genomes, failed


