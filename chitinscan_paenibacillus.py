# 4. Feature table and score
# ----------------------------------------------------------------------
def build_feature_table(hits, genome_names, proteins_per_genome):
    feats = list(PROFILES.values())
    table = pd.DataFrame(0, index=genome_names, columns=feats, dtype=int)
    chit, chit_bind = {g: 0 for g in genome_names}, {g: 0 for g in genome_names}
    if len(hits):
        d = hits.drop_duplicates(["genome", "prot_idx", "feature"])
        for (g, f), n in d.groupby(["genome", "feature"]).size().items():
            table.loc[g, f] = n
        for (g, p), sub in d.groupby(["genome", "prot_idx"]):
            fs = set(sub["feature"])
            if fs & {"GH18_chitinase", "GH19_chitinase"}:
                chit[g] += 1
                if fs & {"CBM5_12_chitin_binding", "FnIII"}:
                    chit_bind[g] += 1
    table["chitinases_GH18_GH19"] = pd.Series(chit)
    table["chitinases_with_binding_module"] = pd.Series(chit_bind)
    table["total_proteins_predicted"] = pd.Series(proteins_per_genome)
    return table


def chitin_score(table):
    w = SCORE_WEIGHTS
    s = pd.Series(0.0, index=table.index)
    s += w["chitinase_present"] * (table["chitinases_GH18_GH19"] >= 1)
    s += w["chitinase_multi"] * (table["chitinases_GH18_GH19"] >= 3)
    s += w["chitinase_binding"] * (table["chitinases_with_binding_module"] >= 1)
    s += w["AA10_LPMO"] * (table["AA10_LPMO"] >= 1)
    s += w["GH20_hexosaminidase"] * (table["GH20_hexosaminidase"] >= 1)
    s += w["GH46_chitosanase"] * (table["GH46_chitosanase"] >= 1)
    return s.astype(int)


def plot_heatmap(table, score):
    cols = ["chitinases_GH18_GH19", "GH18_chitinase", "GH19_chitinase", "chitinases_with_binding_module",
            "AA10_LPMO", "GH20_hexosaminidase", "GH46_chitosanase", "CBM5_12_chitin_binding",
            "FnIII", "LysM", "CE4_deacetylase"]
    order = score.sort_values(ascending=False).index
    data = table.loc[order, cols]
    fig, ax = plt.subplots(figsize=(1.0 * len(cols) + 3, 0.38 * len(order) + 2.5))
    im = ax.imshow(np.log1p(data.values), cmap="YlGnBu", aspect="auto")
    ax.set_xticks(range(len(cols)), cols, rotation=60, ha="right")
    ax.set_yticks(range(len(order)), [f"{g}  (score {score[g]})" for g in order])
    for i in range(data.shape[0]):
        for j in range(data.shape[1]):
            ax.text(j, i, int(data.values[i, j]), ha="center", va="center", fontsize=8,
                    color="white" if np.log1p(data.values[i, j]) > 1.6 else "black")
    ax.set_title("Chitin-related protein counts per genome (colour = log scale)")
    fig.colorbar(im, ax=ax, shrink=0.6, label="log(1 + count)")
    fig.tight_layout()
    fig.savefig(OUT / "chitin_heatmap.png", dpi=200, bbox_inches="tight")
    plt.show()
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 0.35 * len(order) + 2))
    ax.barh(list(order)[::-1], score[order].values[::-1], color="seagreen")
    ax.set_xlabel(f"Chitin-degradation score (0-{sum(SCORE_WEIGHTS.values())})")
    ax.set_title("Genomic chitin-degradation potential (heuristic)")
    fig.tight_layout()
    fig.savefig(OUT / "chitin_score_ranking.png", dpi=200, bbox_inches="tight")
    plt.show()
    plt.close(fig)


