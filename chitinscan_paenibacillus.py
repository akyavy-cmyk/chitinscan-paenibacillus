# 2. Gene prediction (pyrodigal)
# ----------------------------------------------------------------------
def predict_proteins(contigs):
    """Return list of dicts: contig, start, end, strand, protein."""
    import pyrodigal
    seqs = list(contigs.items())
    total = sum(len(s) for _, s in seqs)
    finder = None
    if total >= 100_000:
        try:
            finder = pyrodigal.GeneFinder(meta=False)
            finder.train(*[s for _, s in seqs])
        except Exception:
            finder = None
    if finder is None:                       # tiny / odd sequences: metagenomic models
        finder = pyrodigal.GeneFinder(meta=True)
    prots = []
    for cname, s in seqs:
        for g in finder.find_genes(s):
            aa = g.translate().rstrip("*")
            if len(aa) >= 30:
                prots.append({"contig": cname, "start": g.begin, "end": g.end,
                              "strand": "+" if g.strand == 1 else "-", "protein": aa})
    return prots


