def train_model(table, score):
    if not LABELS_CSV:
        return
    try:
        from sklearn.linear_model import LogisticRegression
        from sklearn.model_selection import LeaveOneOut, cross_val_predict
        from sklearn.preprocessing import StandardScaler
        from sklearn.pipeline import make_pipeline
    except ImportError:
        print("scikit-learn not available; skipping the model.")
        return
    lab = pd.read_csv(LABELS_CSV)
    lab.columns = [c.strip().lower() for c in lab.columns]
    y = lab.set_index("genome")["chitin_degrader"].astype(str).str.lower().map(
        {"1": 1, "yes": 1, "y": 1, "true": 1, "0": 0, "no": 0, "n": 0, "false": 0}).dropna().astype(int)
    common = [g for g in table.index if g in y.index]
    print(f"\nLabelled genomes found in the table: {len(common)} of {len(table)}")
    if len(common) < 8 or y[common].nunique() < 2 or y[common].value_counts().min() < 2:
        print("Not enough labelled genomes of both classes for a meaningful model (need >=2 of each, ideally >=10).")
        return
    X = table.loc[common].drop(columns=["total_proteins_predicted"])
    X = np.log1p(X)
    model = make_pipeline(StandardScaler(), LogisticRegression(class_weight="balanced", max_iter=1000, C=0.5))
    pred = cross_val_predict(model, X, y[common], cv=LeaveOneOut())
    acc = (pred == y[common].values).mean()
    print(f"Leave-one-genome-out accuracy: {acc:.2f} ({int((pred == y[common].values).sum())}/{len(common)})")
    print(pd.crosstab(pd.Series(y[common].values, name="true"), pd.Series(pred, name="predicted")))
    base = ((score[common] >= 3).astype(int).values == y[common].values).mean()
    print(f"For comparison, the simple rule 'score >= 3' scores {base:.2f}")
    model.fit(X, y[common])
    coefs = pd.Series(model[-1].coef_[0], index=X.columns).sort_values(key=abs, ascending=False)
    coefs.to_csv(OUT / "model_coefficients.csv", header=["coefficient"])
    print("\nStrongest features:\n", coefs.head(8).round(2).to_string())
    pd.DataFrame({"genome": common, "true": y[common].values, "predicted_loo": pred}).to_csv(
        OUT / "model_predictions.csv", index=False)


